// Export builders: one table definition shared by XLSX, CSV and PDF.
// Columns = original columns (minus the ones the app manages) +
//           Present, Bus, Seat, Remarks, Check-in Time.

import { getXLSX } from './vendor.js';
import { STATUS } from '../domain/model.js';
import { prettyDate } from '../utils/format.js';

export const APP_COLUMNS = ['Present', 'Bus', 'Seat', 'Remarks', 'Check-in Time'];
export const ABSENT_FILL = 'FDE2E2';

/** @returns {{ headers: string[], rows: {cells: string[], absent: boolean, status: string|null}[], counts: object }} */
export function buildExportTable(store) {
  const cols = store.event.columns || { headers: ['Name', 'ID'], reused: {} };
  const managed = new Set(Object.values(cols.reused || {}).filter(Boolean));
  const original = (cols.headers || []).filter((h) => !managed.has(h));
  // Avoid clashing names if the source already had e.g. "Bus" in another sense.
  const appHeaders = APP_COLUMNS.map((h) => (original.includes(h) ? `${h} (app)` : h));
  const headers = [...original, ...appHeaders];
  const rows = store.participants.map((p) => {
    const a = store.getAttendance(p.id);
    const seat = store.seatLabelOf(p.id);
    const status = a.status || null;
    const present = status === STATUS.PRESENT ? 'Present' : status === STATUS.ABSENT ? 'Absent' : '';
    const cells = [
      ...original.map((h) => String(p.original?.[h] ?? (h === cols.name ? p.name : h === cols.id ? p.studentId : ''))),
      present,
      seat?.bus || '',
      seat?.label || '',
      a.remarks || '',
      status === STATUS.PRESENT ? a.time || '' : '',
    ];
    return { cells, absent: status === STATUS.ABSENT, status };
  });
  return { headers, rows, counts: store.counts() };
}

export function eventInfoLines(store) {
  const ev = store.event;
  const c = store.counts();
  return {
    title: ev.name || 'Attendance',
    meta: [ev.date ? prettyDate(ev.date) : '', ev.venue, ev.picName ? `PIC: ${ev.picName}` : ''].filter(Boolean),
    counts: `Total ${c.total} · Present ${c.present} · Absent ${c.absent} · Unmarked ${c.unmarked}`,
    c,
  };
}

// ── CSV ─────────────────────────────────────────────────────────────────────
const NUMERIC = /^-?(0|[1-9]\d{0,14})(\.\d+)?$/;

function csvCell(v) {
  let s = String(v ?? '');
  // Neutralise spreadsheet formula injection (=, +, -, @ at the start).
  if (/^[=+\-@\t\r]/.test(s) && !NUMERIC.test(s)) s = `'${s}`;
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function toCSV(table) {
  const lines = [table.headers, ...table.rows.map((r) => r.cells)].map((r) => r.map(csvCell).join(','));
  // BOM so Excel opens UTF-8 correctly; CRLF per RFC 4180.
  return new Blob(['﻿' + lines.join('\r\n') + '\r\n'], { type: 'text/csv;charset=utf-8' });
}

// ── XLSX ────────────────────────────────────────────────────────────────────
export async function toXLSX(table, store) {
  const XLSX = await getXLSX();
  const aoa = [table.headers, ...table.rows.map((r) => r.cells.map((v) => (NUMERIC.test(v) && v.length < 15 ? Number(v) : v)))];
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  const border = { style: 'thin', color: { rgb: 'CBD5E1' } };
  table.headers.forEach((_, c) => {
    const ref = XLSX.utils.encode_cell({ r: 0, c });
    ws[ref].s = { font: { bold: true }, border: { bottom: { style: 'medium', color: { rgb: '64748B' } } }, alignment: { vertical: 'center' } };
  });
  table.rows.forEach((row, i) => {
    if (!row.absent) return;
    table.headers.forEach((_, c) => {
      const ref = XLSX.utils.encode_cell({ r: i + 1, c });
      if (!ws[ref]) ws[ref] = { t: 's', v: '' };
      ws[ref].s = { fill: { patternType: 'solid', fgColor: { rgb: ABSENT_FILL } }, border: { bottom: border } };
    });
  });
  ws['!cols'] = table.headers.map((h, c) => ({
    wch: Math.min(48, Math.max(String(h).length + 2, ...table.rows.slice(0, 500).map((r) => String(r.cells[c] ?? '').length + 1), 6)),
  }));
  ws['!autofilter'] = { ref: XLSX.utils.encode_range({ s: { r: 0, c: 0 }, e: { r: table.rows.length, c: table.headers.length - 1 } }) };

  const info = eventInfoLines(store);
  const ev = store.event;
  const summary = XLSX.utils.aoa_to_sheet([
    ['Event', ev.name || ''],
    ['Date', ev.date || ''],
    ['Venue', ev.venue || ''],
    ['PIC', ev.picName || ''],
    [],
    ['Total', info.c.total],
    ['Present', info.c.present],
    ['Absent', info.c.absent],
    ['Unmarked', info.c.unmarked],
    ['Buses', store.buses.length],
    [],
    ['Generated', new Date().toLocaleString()],
    ['Generated by', 'Attendance PIC (offline)'],
  ]);
  summary['!cols'] = [{ wch: 14 }, { wch: 40 }];
  for (let r = 0; r < 13; r++) {
    const ref = XLSX.utils.encode_cell({ r, c: 0 });
    if (summary[ref]) summary[ref].s = { font: { bold: true } };
  }
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Attendance');
  XLSX.utils.book_append_sheet(wb, summary, 'Event');
  wb.Props = { Title: `Attendance – ${ev.name || ''}`, Author: ev.picName || 'Attendance PIC', CreatedDate: new Date() };
  const out = XLSX.write(wb, { bookType: 'xlsx', type: 'array', compression: true });
  return new Blob([out], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
}

// ── JSON backup ─────────────────────────────────────────────────────────────
export async function toBackup(store) {
  const snap = await store.exportBackup();
  return new Blob([JSON.stringify(snap, null, 1)], { type: 'application/json' });
}
